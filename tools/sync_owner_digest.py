#!/usr/bin/env python3
"""Single source of truth for the owner e-mail SHA-256 digest.

The digest gates the web owner dashboard twice:

* `owner-auth.js`      — browser-side gate (decides whether to reveal the dashboard)
* `supabase_schema.sql` — server-side enforcement (`public.is_cafedesk_owner()` via RLS)

Keeping two copies of a hash in hand-sync is how the dashboard ends up logging
in while silently seeing nothing. The digest now lives in exactly one place:
`OWNER_EMAIL_SHA256` below. Both files carry marked, generated blocks.

Usage:
    python tools/sync_owner_digest.py           # rewrite both files from the constant
    python tools/sync_owner_digest.py --check   # exit 1 on drift (used by CI)

To rotate the owner account:
    1. Compute  sha256("CAFE-DESK-OWNER-V1|" + lower(trim(new-owner-email)))  as hex
    2. Paste it into OWNER_EMAIL_SHA256 below
    3. Run `python tools/sync_owner_digest.py` and commit all three files together
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

DIGEST_DOMAIN = 'CAFE-DESK-OWNER-V1|'  # documentation only — changing it invalidates the digest

# sha256("CAFE-DESK-OWNER-V1|" + owner email, lowercased & trimmed), hex.
OWNER_EMAIL_SHA256 = '72f63f593e8b7db71539bdb0c9ed04567a072b946102b1f353a049870b9ba1bc'


def js_block() -> str:
    return (
        '  // OWNER-DIGEST-BEGIN (generated by tools/sync_owner_digest.py — do not edit by hand)\n'
        '  var OWNER_EMAIL_SHA256 =\n'
        f'    "{OWNER_EMAIL_SHA256}";\n'
        '  // OWNER-DIGEST-END\n'
    )


def sql_block() -> str:
    return (
        '-- OWNER-DIGEST-BEGIN (generated by tools/sync_owner_digest.py — do not edit by hand)\n'
        'create or replace function public.cafedesk_owner_digest()\n'
        'returns text\n'
        'language sql\n'
        'immutable\n'
        'as $$\n'
        f"    select '{OWNER_EMAIL_SHA256}';\n"
        '$$;\n'
        '-- OWNER-DIGEST-END\n'
    )


def replace_block(text: str, begin: str, end: str, block: str, rel: str) -> str:
    pattern = re.compile(re.escape(begin) + r'.*?' + re.escape(end) + r'\n?', re.DOTALL)
    if not pattern.search(text):
        raise SystemExit(f'{rel}: OWNER-DIGEST markers not found — add the generated block markers first.')
    return pattern.sub(lambda _m: block, text, count=1)


def targets():
    return [
        ('owner-auth.js', '  // OWNER-DIGEST-BEGIN', '  // OWNER-DIGEST-END', js_block()),
        ('supabase_schema.sql', '-- OWNER-DIGEST-BEGIN', '-- OWNER-DIGEST-END', sql_block()),
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='exit 1 if the files drifted from the constant')
    args = parser.parse_args()

    problems: list[str] = []
    for rel, begin, end, block in targets():
        path = ROOT / rel
        text = path.read_text(encoding='utf-8')
        updated = replace_block(text, begin, end, block, rel)
        if args.check:
            if updated != text:
                problems.append(f'{rel} is out of sync with OWNER_EMAIL_SHA256 in tools/sync_owner_digest.py')
        else:
            path.write_text(updated, encoding='utf-8')
            print(f'Updated {rel}')

    for problem in problems:
        print(f'::error::{problem}')
    if problems:
        print('Run `python tools/sync_owner_digest.py` and commit the result.')
        return 1
    if args.check:
        print('Owner digest in sync (owner-auth.js == supabase_schema.sql == OWNER_EMAIL_SHA256).')
    return 0


if __name__ == '__main__':
    sys.exit(main())
