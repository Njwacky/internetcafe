"""Verify which owner signing key is embedded in a PUBLISHED Café Desk build.

Why this exists
---------------
`check_release_key.py` runs at BUILD time and fails closed when the demo key would
ship. That still leaves one question a build log cannot answer from the outside:
*is the key inside the file I am handing to a customer actually mine?*

This tool answers that by inspecting the artifact itself. Use it on the exact file
you download from the GitHub Releases page, so you are checking what customers get
rather than what you think the pipeline did.

Usage
-----
    # Check the portable ZIP (inspects compiled Python bytecode inside CafeDesk.exe):
    python tools/verify_release_key.py CafeDesk-Windows-USB-Portable.zip

    # Check the single-file installer or an installed CafeDesk.exe:
    python tools/verify_release_key.py CafeDesk-Setup.exe
    python tools/verify_release_key.py dist/CafeDesk/CafeDesk.exe

    # If owner-keys/ is present the expected key is read automatically; override with:
    python tools/verify_release_key.py build.zip --expect <base64url-public-key>

    # Also verify that the embedded key matches Supabase's app_releases Ed25519 signature:
    python tools/verify_release_key.py CafeDesk-Windows-USB-Portable.zip \
        --verify-release-sig 0.8.5 <signature-from-supabase-app_releases>

Exit codes: 0 = correct key found, 1 = demo key found / key missing / mismatch, 2 = bad input.

How it works
------------
PyInstaller compresses pure-Python modules (`license_guard`) with zlib inside a `PYZ`
archive embedded in `CafeDesk.exe`'s `CArchive` (`MEI\\x0c\\x0b\\x0a\\x0b\\x0e`), while
Inno Setup solid-compresses `CafeDesk-Setup.exe` with LZMA2 (carrying an uncompressed
`CAFEDESK-EMBEDDED-PUBLIC-KEY-V1:` metadata record generated by `check_release_key.py`).

This verifier:
1. Parses PyInstaller `CArchive` and `PYZ` archives (pure Python `struct` + `zlib`,
   including cross-Python-version marshalled constant extraction) to read the exact
   `DEFAULT_OWNER_PUBLIC_KEY_B64` compiled into `license_guard`.
2. Reads uncompressed `CAFEDESK-EMBEDDED-PUBLIC-KEY-V1:<key>` records in `CafeDesk-Setup.exe`.
3. Falls back to chunked raw bytecode scanning for unpacked `.pyc` test fixtures while
   avoiding false-positive symbol names in native `.dll`/`.pyd`/`.so` libraries.
"""
from __future__ import annotations

import argparse
import base64
import dis
import hashlib
import io
import marshal
import os
import re
import struct
import sys
import zipfile
import zlib
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEMO_KEY_FALLBACK = 'tuAEglg-NweqdIgh4Jbojl4yQW4iWMOd3fLEbLMV7lI'
LOCAL_PUB_PATH = REPO_ROOT / 'owner-keys' / 'cafedesk_owner.public.txt'
RELEASE_KEY_META_RE = re.compile(rb'CAFEDESK-EMBEDDED-PUBLIC-KEY-V1:([A-Za-z0-9_-]{43})')
INNO_SETUP_MARKER = b'Inno Setup Setup Data'

# Documentation / data members of the portable ZIP (README.md, the HTML manuals,
# HOW-TO-RUN-FROM-USB.txt, fonts, icons, ...). The bundled README quotes the demo key
# as an example for the owner's find/replace step, which is harmless — the key only
# matters as the active verification constant in Python bytecode. Mirrors
# `_DATA_FILE_EXTENSIONS` in .github/check_release_key.py (keep in sync).
_DATA_MEMBER_SUFFIXES = frozenset({
    '.md', '.txt', '.html', '.htm', '.rst', '.json', '.csv', '.tsv', '.xml',
    '.pdf', '.css', '.svg', '.png', '.jpg', '.jpeg', '.gif', '.bmp', '.ico',
    '.webp', '.tif', '.tiff', '.ttf', '.otf', '.woff', '.woff2', '.eot',
    '.mp3', '.wav', '.ogg', '.mp4', '.zip', '.gz', '.tar', '.7z', '.log',
    '.yaml', '.yml', '.toml', '.ini', '.cfg', '.map', '.lock',
})
_NATIVE_BINARY_SUFFIXES = frozenset({'.dll', '.pyd', '.so', '.dylib'})

_B64U_RE = re.compile(r'^[A-Za-z0-9_-]{43}$')
_RUN_RE = re.compile(rb'[A-Za-z0-9_-]{43,}')
_CHUNK = 8 * 1024 * 1024
_CARRY = 96

_PKG_COOKIE_MAGIC = b'MEI\x0c\x0b\x0a\x0b\x0e'
_PKG_COOKIE_FORMAT = '!8sIIII64s'
_PKG_COOKIE_LEN = struct.calcsize(_PKG_COOKIE_FORMAT)
_PKG_TOC_ENTRY_FORMAT = '!IIIIBc'
_PKG_TOC_ENTRY_LEN = struct.calcsize(_PKG_TOC_ENTRY_FORMAT)
_PYZ_MAGIC = b'PYZ\x00'
_SHORT_ASCII_43_RE = re.compile(rb'[\x5a\xda\x7a\xfa]\x2b([A-Za-z0-9_-]{43})')
_LONG_ASCII_43_RE = re.compile(rb'[\x41\xc1\x61\xe1\x73\xf3\x75\xf5]\x2b\x00\x00\x00([A-Za-z0-9_-]{43})')
_PYZ_TOC_FALLBACK_RE = re.compile(
    rb'[\x5a\xda\x7a\xfa]\x0dlicense_guard[\x29\xa9]\x03[\x69\xe9](.{4})[\x69\xe9](.{4})[\x69\xe9](.{4})',
    re.DOTALL,
)


def _demo_key() -> str:
    """The fixed sample demo public key (never `DEFAULT_OWNER_PUBLIC_KEY_B64`, which an owner may replace)."""
    return DEMO_KEY_FALLBACK


def _expected_key(explicit: str | None) -> str:
    if explicit:
        return explicit.strip().strip('"').strip("'")
    try:
        return LOCAL_PUB_PATH.read_text(encoding='utf-8').strip()
    except OSError:
        return ''


def _is_keyish(token: bytes) -> bool:
    """True when 43 base64url chars decode to exactly 32 bytes (an Ed25519 key)."""
    if len(token) != 43:
        return False
    try:
        return len(base64.urlsafe_b64decode(token + b'=')) == 32
    except Exception:
        return False


def _extract_keys_from_marshalled_guard(raw_code: bytes, demo_key: str) -> list[str]:
    """Extract `DEFAULT_OWNER_PUBLIC_KEY_B64` from marshalled `license_guard` code bytes."""
    for candidate_blob in (raw_code, raw_code[16:] if len(raw_code) > 16 else b''):
        if not candidate_blob:
            continue
        try:
            code_obj = marshal.loads(candidate_blob)
        except Exception:
            code_obj = None
        if code_obj is not None and hasattr(code_obj, 'co_code'):
            last_const = None
            try:
                for instr in dis.get_instructions(code_obj):
                    if instr.opname == 'LOAD_CONST':
                        last_const = instr.argval
                    elif instr.opname in ('STORE_NAME', 'STORE_GLOBAL') and instr.argval == 'DEFAULT_OWNER_PUBLIC_KEY_B64':
                        if isinstance(last_const, str) and last_const:
                            return [last_const.strip()]
                        last_const = None
                    else:
                        last_const = None
            except Exception:
                pass

    # Cross-Python-version fallback when `marshal.loads` rejects `TYPE_CODE` from
    # another Python minor release (e.g. Python 3.12+ inspecting a Python 3.11 EXE).
    ordered: list[str] = []
    for regex in (_SHORT_ASCII_43_RE, _LONG_ASCII_43_RE):
        for match in regex.finditer(raw_code):
            raw_tok = match.group(1)
            if _is_keyish(raw_tok):
                val = raw_tok.decode('ascii')
                if val not in ordered:
                    ordered.append(val)
    if len(ordered) == 2 and ordered[0] == demo_key and ordered[1] != demo_key:
        return [ordered[1]]
    return ordered


def _extract_guard_keys_from_pyz_bytes(pyz_blob: bytes, demo_key: str) -> list[str]:
    if len(pyz_blob) < 17 or pyz_blob[:4] != _PYZ_MAGIC:
        return []
    toc_offset = struct.unpack('!i', pyz_blob[8:12])[0]
    if toc_offset <= 0 or toc_offset >= len(pyz_blob):
        return []
    toc_bytes = pyz_blob[toc_offset:]
    entry_loc: tuple[int, int] | None = None
    try:
        toc_obj = marshal.loads(toc_bytes)
        if isinstance(toc_obj, dict) and 'license_guard' in toc_obj:
            _, pos, length = toc_obj['license_guard']
            entry_loc = (int(pos), int(length))
        elif isinstance(toc_obj, list):
            for item in toc_obj:
                if isinstance(item, tuple) and len(item) == 2 and item[0] == 'license_guard':
                    _, pos, length = item[1]
                    entry_loc = (int(pos), int(length))
                    break
    except Exception:
        entry_loc = None

    if entry_loc is None:
        m = _PYZ_TOC_FALLBACK_RE.search(toc_bytes)
        if m:
            _, pos, length = (struct.unpack('<i', m.group(i))[0] for i in (1, 2, 3))
            entry_loc = (pos, length)

    if entry_loc is None:
        return []
    pos, length = entry_loc
    if pos < 0 or length <= 0 or pos + length > len(pyz_blob):
        return []
    try:
        raw_code = zlib.decompress(pyz_blob[pos:pos + length])
    except zlib.error:
        return []
    return _extract_keys_from_marshalled_guard(raw_code, demo_key)


def _find_pkg_cookie(fh: io.BufferedReader | io.BytesIO, max_tail: int = 16 * 1024 * 1024) -> int:
    fh.seek(0, os.SEEK_END)
    end_pos = fh.tell()
    min_pos = max(0, end_pos - max_tail)
    chunk_size = 65536
    while end_pos - min_pos >= len(_PKG_COOKIE_MAGIC):
        start_pos = max(min_pos, end_pos - chunk_size)
        fh.seek(start_pos, os.SEEK_SET)
        buf = fh.read(end_pos - start_pos)
        pos = buf.rfind(_PKG_COOKIE_MAGIC)
        if pos != -1:
            return start_pos + pos
        if start_pos == min_pos:
            break
        end_pos = start_pos + len(_PKG_COOKIE_MAGIC) - 1
    return -1


def _extract_pyinstaller_stream_keys(fh: io.BufferedReader | io.BytesIO, demo_key: str) -> list[str]:
    found: list[str] = []
    fh.seek(0, os.SEEK_SET)
    head4 = fh.read(4)
    if head4 == _PYZ_MAGIC:
        fh.seek(0, os.SEEK_SET)
        return _extract_guard_keys_from_pyz_bytes(fh.read(), demo_key)

    cookie_pos = _find_pkg_cookie(fh)
    if cookie_pos < 0:
        return []
    fh.seek(cookie_pos, os.SEEK_SET)
    cookie_buf = fh.read(_PKG_COOKIE_LEN)
    if len(cookie_buf) != _PKG_COOKIE_LEN:
        return []
    _, archive_len, toc_off, toc_len, _, _ = struct.unpack(_PKG_COOKIE_FORMAT, cookie_buf)
    end_offset = cookie_pos + _PKG_COOKIE_LEN
    if archive_len <= 0 or toc_len <= 0 or archive_len > end_offset or toc_off + toc_len > archive_len:
        return []
    pkg_start = end_offset - archive_len
    fh.seek(pkg_start + toc_off, os.SEEK_SET)
    toc_data = fh.read(toc_len)
    cur = 0
    while cur + _PKG_TOC_ENTRY_LEN <= len(toc_data):
        entry_len, entry_off, data_len, _, comp_flag, typecode = struct.unpack(
            _PKG_TOC_ENTRY_FORMAT, toc_data[cur:cur + _PKG_TOC_ENTRY_LEN]
        )
        if entry_len < _PKG_TOC_ENTRY_LEN or cur + entry_len > len(toc_data):
            break
        raw_name = toc_data[cur + _PKG_TOC_ENTRY_LEN:cur + entry_len]
        cur += entry_len
        name = raw_name.rstrip(b'\x00').decode('utf-8', errors='replace')
        tc = typecode.decode('ascii', errors='replace')
        if tc == 'z':
            fh.seek(pkg_start + entry_off, os.SEEK_SET)
            pyz_blob = fh.read(data_len)
            if comp_flag:
                try:
                    pyz_blob = zlib.decompress(pyz_blob)
                except zlib.error:
                    continue
            for k in _extract_guard_keys_from_pyz_bytes(pyz_blob, demo_key):
                if k not in found:
                    found.append(k)
        elif tc in ('m', 'M', 's') and name in ('license_guard', 'license_guard.py', 'license_guard.pyc'):
            fh.seek(pkg_start + entry_off, os.SEEK_SET)
            mod_blob = fh.read(data_len)
            if comp_flag:
                try:
                    mod_blob = zlib.decompress(mod_blob)
                except zlib.error:
                    continue
            for k in _extract_keys_from_marshalled_guard(mod_blob, demo_key):
                if k not in found:
                    found.append(k)
    return found


def _scan_bytes(blob: bytes, found: set[str], known: set[str]) -> None:
    """Collect key-looking strings from a raw byte chunk (fallback for unpacked `.pyc` files)."""
    for key in known:
        if key and key.encode('ascii') in blob:
            found.add(key)
    for match in _RUN_RE.finditer(blob):
        run = match.group(0)
        if len(run) == 43:
            if _is_keyish(run):
                found.add(run.decode('ascii'))
            continue
        for i in range(0, len(run) - 42):
            window = run[i:i + 43]
            if _is_keyish(window):
                found.add(window.decode('ascii'))
                break


def _scan_meta_stamps_and_inno(path: Path) -> tuple[list[str], bool, str]:
    """Single streaming pass over `path` returning `(stamp_keys, is_inno_setup, sha256_hex)`."""
    stamps: list[str] = []
    is_inno = False
    digest = hashlib.sha256()
    with path.open('rb') as fh:
        carry = b''
        while True:
            chunk = fh.read(_CHUNK)
            if not chunk:
                window = carry
                for m in RELEASE_KEY_META_RE.finditer(window):
                    tok = m.group(1)
                    if _is_keyish(tok):
                        s = tok.decode('ascii')
                        if s not in stamps:
                            stamps.append(s)
                if INNO_SETUP_MARKER in window:
                    is_inno = True
                break
            digest.update(chunk)
            window = carry + chunk
            for m in RELEASE_KEY_META_RE.finditer(window):
                tok = m.group(1)
                if _is_keyish(tok):
                    s = tok.decode('ascii')
                    if s not in stamps:
                        stamps.append(s)
            if not is_inno and INNO_SETUP_MARKER in window:
                is_inno = True
            carry = chunk[-_CARRY:]
    return stamps, is_inno, digest.hexdigest()


def scan_file(path: Path, found: set[str], known: set[str]) -> int:
    """Scan a raw file in chunks. Returns bytes scanned."""
    total = 0
    with path.open('rb') as fh:
        carry = b''
        while True:
            chunk = fh.read(_CHUNK)
            if not chunk:
                _scan_bytes(carry, found, known)
                break
            _scan_bytes(carry + chunk, found, known)
            carry = chunk[-_CARRY:]
            total += len(chunk)
    return total


def scan_zip(path: Path, found: set[str], known: set[str]) -> list[str]:
    """Inspect a portable ZIP for embedded owner keys; returns member names where keys were found.

    Prefers authoritative PyInstaller CArchive/PYZ `license_guard` bytecode and
    `release-key.meta` stamps so native `.dll`/`.pyd`/`.so` symbol tables never pollute
    the report. Falls back to raw chunked scanning for synthetic `.pyc` test archives.
    """
    demo = _demo_key()
    authoritative_hits: list[str] = []
    with zipfile.ZipFile(path) as zf:
        for info in zf.infolist():
            if info.is_dir():
                continue
            member_path = Path(info.filename)
            suffix = member_path.suffix.lower()
            if suffix in _DATA_MEMBER_SUFFIXES:
                continue
            try:
                if member_path.name == 'release-key.meta' and info.file_size <= 65536:
                    blob = zf.read(info)
                    before = len(found)
                    for m in RELEASE_KEY_META_RE.finditer(blob):
                        if _is_keyish(m.group(1)):
                            found.add(m.group(1).decode('ascii'))
                    if len(found) > before:
                        authoritative_hits.append(info.filename)
                elif suffix in ('', '.exe', '.pkg', '.pyz') and 17 <= info.file_size <= 64 * 1024 * 1024:
                    buf = io.BytesIO(zf.read(info))
                    pyz_keys = _extract_pyinstaller_stream_keys(buf, demo)
                    if pyz_keys:
                        found.update(pyz_keys)
                        authoritative_hits.append(info.filename)
            except (zipfile.BadZipFile, OSError, RuntimeError):
                continue

        if authoritative_hits:
            return authoritative_hits

        # Fallback for unpacked `.pyc` archives or synthetic test fixtures (skip native
        # shared libraries first so C/Rust symbol names do not masquerade as Ed25519 keys).
        hits: list[str] = []
        for skip_native in (True, False):
            for info in zf.infolist():
                if info.is_dir():
                    continue
                suffix = Path(info.filename).suffix.lower()
                if suffix in _DATA_MEMBER_SUFFIXES:
                    continue
                if skip_native and suffix in _NATIVE_BINARY_SUFFIXES:
                    continue
                if not skip_native and suffix not in _NATIVE_BINARY_SUFFIXES:
                    continue
                try:
                    with zf.open(info) as member:
                        before = len(found)
                        carry = b''
                        while True:
                            chunk = member.read(_CHUNK)
                            if not chunk:
                                _scan_bytes(carry, found, known)
                                break
                            _scan_bytes(carry + chunk, found, known)
                            carry = chunk[-_CARRY:]
                        if len(found) > before:
                            hits.append(info.filename)
                except (zipfile.BadZipFile, OSError, RuntimeError):
                    continue
            if found:
                break
    return hits


def _scan_directory(folder: Path, found: set[str], known: set[str]) -> list[str]:
    demo = _demo_key()
    hits: list[str] = []
    for path in sorted(folder.rglob('*')):
        if not path.is_file():
            continue
        suffix = path.suffix.lower()
        if suffix in _DATA_MEMBER_SUFFIXES:
            continue
        try:
            size = path.stat().st_size
            if path.name == 'release-key.meta' and size <= 65536:
                blob = path.read_bytes()
                before = len(found)
                for m in RELEASE_KEY_META_RE.finditer(blob):
                    if _is_keyish(m.group(1)):
                        found.add(m.group(1).decode('ascii'))
                if len(found) > before:
                    hits.append(str(path.relative_to(folder)))
            elif suffix in ('', '.exe', '.pkg', '.pyz') and 17 <= size <= 128 * 1024 * 1024:
                with path.open('rb') as fh:
                    pyz_keys = _extract_pyinstaller_stream_keys(fh, demo)
                if pyz_keys:
                    found.update(pyz_keys)
                    hits.append(str(path.relative_to(folder)))
        except OSError:
            continue
    if hits:
        return hits
    for path in sorted(folder.rglob('*')):
        if not path.is_file():
            continue
        suffix = path.suffix.lower()
        if suffix in _DATA_MEMBER_SUFFIXES or suffix in _NATIVE_BINARY_SUFFIXES:
            continue
        before = len(found)
        scan_file(path, found, known)
        if len(found) > before:
            hits.append(str(path.relative_to(folder)))
    return hits


def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as fh:
        while True:
            chunk = fh.read(_CHUNK)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()


def _verify_release_signature(version: str, sha256_hex: str, signature_b64: str, pub_key_b64: str) -> bool:
    if str(REPO_ROOT) not in sys.path:
        sys.path.insert(0, str(REPO_ROOT))
    import cloud_sync  # Imported lazily so plain artifact scans need zero third-party deps
    return cloud_sync.verify_release_signature(version, sha256_hex, signature_b64, pub_key_b64)


def _normalize_argv_leading_hyphen_tokens(raw_argv: list[str]) -> list[str]:
    """Allow base64url keys/signatures starting with `-` after `--expect` or `--verify-release-sig`."""
    out: list[str] = []
    i = 0
    while i < len(raw_argv):
        arg = raw_argv[i]
        if arg == '--expect' and i + 1 < len(raw_argv):
            out.append(f'--expect={raw_argv[i + 1]}')
            i += 2
            continue
        if arg == '--verify-release-sig' and i + 2 < len(raw_argv):
            # Prefix a leading space if the signature begins with `-` so argparse accepts it as a value;
            # `verify_release_signature` strips surrounding whitespace.
            ver_arg = raw_argv[i + 1]
            sig_arg = raw_argv[i + 2]
            if sig_arg.startswith('-'):
                sig_arg = ' ' + sig_arg
            out.extend([arg, ver_arg, sig_arg])
            i += 3
            continue
        out.append(arg)
        i += 1
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description='Check which owner Ed25519 public key is embedded in a Café Desk release artifact.')
    parser.add_argument('artifact', help='CafeDesk-Windows-USB-Portable.zip, CafeDesk-Setup.exe, CafeDesk.exe, or dist/CafeDesk')
    parser.add_argument('--expect', help='Expected public key (default: owner-keys/cafedesk_owner.public.txt)')
    parser.add_argument(
        '--verify-release-sig',
        nargs=2,
        metavar=('VERSION', 'SIGNATURE'),
        help='Also verify that the embedded public key validates the Ed25519 release signature for VERSION over this file\'s SHA-256.',
    )
    norm_argv = _normalize_argv_leading_hyphen_tokens(list(sys.argv[1:] if argv is None else argv))
    args = parser.parse_args(norm_argv)

    target = Path(args.artifact)
    if not target.exists():
        print(f'ERROR: file not found: {target}', file=sys.stderr)
        return 2

    expected = _expected_key(args.expect)
    demo = _demo_key()
    found: set[str] = set()
    known = {k for k in (expected, demo) if k}
    artifact_sha256 = ''

    if target.is_dir():
        print(f'Scanning folder {target}…')
        members = _scan_directory(target, found, known)
        if members:
            print(f'  keys found inside: {", ".join(members[:4])}'
                  f'{" …" if len(members) > 4 else ""}')
    elif zipfile.is_zipfile(target):
        artifact_sha256 = _sha256_file(target)
        print(f'Scanning {target.name} ({target.stat().st_size:,} bytes, sha256={artifact_sha256})…')
        members = scan_zip(target, found, known)
        if members:
            print(f'  keys found inside: {", ".join(members[:4])}'
                  f'{" …" if len(members) > 4 else ""}')
    else:
        stamps, is_inno, artifact_sha256 = _scan_meta_stamps_and_inno(target)
        print(f'Scanning {target.name} ({target.stat().st_size:,} bytes, sha256={artifact_sha256})…')
        with target.open('rb') as fh:
            pyz_keys = _extract_pyinstaller_stream_keys(fh, demo)
        if pyz_keys:
            found.update(pyz_keys)
            print('  keys extracted from PyInstaller bytecode')
        if stamps:
            found.update(stamps)
            print('  keys extracted from uncompressed release-key.meta stamp')
        if not found:
            if is_inno:
                print('\nFAIL: this Inno Setup installer uses solid LZMA2 compression without an')
                print('uncompressed release-key.meta stamp (built before installer stamp support).')
                print('Verify the matching CafeDesk-Windows-USB-Portable.zip from the same release,')
                print('or pass the installed CafeDesk.exe directly to inspect its compiled bytecode.')
                return 1
            scan_file(target, found, known)

    if not found:
        print('\nFAIL: no 32-byte Ed25519 key string was found in this artifact.')
        print('This is unexpected for a PyInstaller build — check you passed the real')
        print('installer/ZIP and not a checksum or shortcut file.')
        return 1

    # Drop shifted 43-char window slices adjacent to a known key in fallback raw scans.
    def _shares_run(candidate: str, known_keys: set[str]) -> bool:
        windows = {candidate[i:i + 20] for i in range(0, max(1, len(candidate) - 19))}
        return any(w and w in k for k in known_keys for w in windows)

    for noise in [k for k in list(found) if k not in (demo, expected) and _shares_run(k, {demo, expected})]:
        found.discard(noise)

    has_demo = demo in found
    has_expected = bool(expected) and expected in found
    others = sorted(found - {demo, expected} - {''})

    print('\nKeys embedded in this artifact:')
    for key in sorted(found):
        key_digest = hashlib.sha256(key.encode('ascii')).hexdigest()
        tag = []
        if expected and key == expected:
            tag.append('YOUR KEY')
        if key == demo:
            tag.append('*** DEMO KEY — DO NOT DISTRIBUTE ***')
        if key in others:
            tag.append('unexpected')
        label = f'   {" ".join(tag)}' if tag else ''
        print(f'  {key}  (sha256={key_digest[:16]}…){label}')
        print(f'    public_key_sha256: {key_digest}')

    print()
    if has_demo:
        print('FAIL: the DEMO signing key is embedded in this file.')
        print('  Do not give this build to a customer. Fix CAFE_DESK_PUBLIC_KEY and rebuild.')
        return 1

    active_non_demo = expected if has_expected else (sorted(found)[0] if len(found) == 1 else '')
    if args.verify_release_sig:
        if not artifact_sha256:
            print('FAIL: --verify-release-sig requires a single release file (.zip or .exe), not a folder.')
            return 2
        rel_ver, rel_sig = args.verify_release_sig
        rel_sig = rel_sig.strip()
        verify_key = active_non_demo or expected
        if not verify_key:
            print('FAIL: multiple candidate keys found; pass --expect <your-public-key> with --verify-release-sig.')
            return 1
        if not _verify_release_signature(rel_ver, artifact_sha256, rel_sig, verify_key):
            print(f'FAIL: Ed25519 release signature verification FAILED for v{rel_ver.lstrip("vV")}.')
            print('  Either the file bytes do not match the signed release SHA-256, or the')
            print('  GitHub Actions CAFE_DESK_PUBLIC_KEY does not match Supabase CAFEDESK_OWNER_PRIVATE_KEY_B64.')
            return 1
        print(f'Release signature OK: embedded key verifies Supabase Ed25519 signature for v{rel_ver.lstrip("vV")}.')

    if not expected:
        print('WARNING: no expected key available (owner-keys/ missing and --expect not given),')
        print('  so this scan could only prove the demo key is absent. Re-run with --expect.')
        return 0
    if has_expected:
        print('PASS: this artifact embeds YOUR owner public key.')
        return 0
    print('FAIL: your expected key was NOT found in this artifact.')
    print(f'  expected: {expected}')
    print('  A build made from a different keypair cannot be activated with your licenses.')
    return 1


